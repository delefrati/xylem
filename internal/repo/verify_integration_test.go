type history struct {
	env                     *repotest.Env
	root, a, b, merge, tail *repo.Changeset
	storeDir                string
}

// newHistory builds root → a → merge(a, b) → tail with b off root, main at tail.
func newHistory(t *testing.T) *history {
	t.Helper()
	dir := t.TempDir()
	env := repotest.NewEnv(t, store.NewFS(dir))
	r := env.Repo
	h := &history{env: env, storeDir: dir}
	h.root = repotest.Commit(t, r, nil, "root", repotest.Put(t, r, "README", "hi"), repotest.Put(t, r, "src/a.go", "a"), repotest.Put(t, r, "src/b.go", "b"))
	h.a = repotest.Commit(t, r, []hash.ID{h.root.ID}, "a", repotest.Put(t, r, "src/a.go", "a2"), repotest.Delete("README"))
	h.b = repotest.Commit(t, r, []hash.ID{h.root.ID}, "b", repotest.Put(t, r, "lib/x/y.go", "y"))
	h.merge = repotest.Commit(t, r, []hash.ID{h.a.ID, h.b.ID}, "merge", repotest.Put(t, r, "lib/x/y.go", "y"))
	h.tail = repotest.Commit(t, r, []hash.ID{h.merge.ID}, "tail", repotest.Delete("src/b.go"))
	ctx := context.Background()
	if _, err := r.UpdateRef(ctx, repo.MainRef, hash.ID{}, h.tail.ID, false, "t", "admin"); err != nil {
		t.Fatal(err)
	}
	if _, err := r.UpdateRef(ctx, "release/1", hash.ID{}, h.a.ID, false, "t", "admin"); err != nil {
		t.Fatal(err)
	}
	return h
}

func (h *history) exec(t *testing.T, sql string, args ...any) {
	t.Helper()
	if _, err := h.env.Pool.Exec(context.Background(), sql, args...); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
}

// verify reopens the repo (cold caches, so tampered rows are actually read).
func (h *history) verify(t *testing.T, opts repo.VerifyOptions) *repo.VerifyReport {
	t.Helper()
	r, err := repo.Open(context.Background(), h.env.Meta, h.env.Objects, "default", repo.Options{})
	if err != nil {
		t.Fatal(err)
	}
	report, err := r.Verify(context.Background(), opts)
	if err != nil {
		t.Fatalf("Verify: %v", err)
	}
	return report
}

func TestVerifyClean(t *testing.T) {
	t.Parallel()
	h := newHistory(t)
	report := h.verify(t, repo.VerifyOptions{Objects: true})
	if len(report.Violations) != 0 || report.Changesets != 5 || report.Refs != 2 {
		t.Errorf("clean history: %d changesets, %d refs, violations %v", report.Changesets, report.Refs, report.Violations)
	}
	sample := h.verify(t, repo.VerifyOptions{Sample: 3, Objects: true})
	if len(sample.Violations) != 0 || sample.Changesets != 3 {
		t.Errorf("sample: %d changesets, violations %v", sample.Changesets, sample.Violations)
	}
}

func TestVerifyDetectsTampering(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		tamper func(t *testing.T, h *history)
		check  string
		opts   repo.VerifyOptions
	}{
		{"root tree", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE core_derived SET root_tree = $1 WHERE changeset_id = $2", h.root.Core.RootTree[:], h.a.ID[:])
		}, "root_tree", repo.VerifyOptions{}},
		{"gen", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE core_derived SET gen = gen + 1 WHERE changeset_id = $1", h.merge.ID[:])
		}, "core", repo.VerifyOptions{}},
		{"jump", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE core_derived SET fp_jump = $1 WHERE changeset_id = $2", h.tail.ID[:], h.tail.ID[:])
		}, "core", repo.VerifyOptions{}},
		{"body", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE changesets SET body = body || '\\x00'::bytea WHERE id = $1", h.b.ID[:])
		}, "body", repo.VerifyOptions{}},
		{"summary column", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE changesets SET summary = 'edited' WHERE id = $1", h.b.ID[:])
		}, "columns", repo.VerifyOptions{}},
		{"file row", func(t *testing.T, h *history) {
			h.exec(t, "DELETE FROM changeset_files WHERE changeset_id = $1 AND path = 'README'", h.a.ID[:])
		}, "files", repo.VerifyOptions{}},
		{"seq order", func(t *testing.T, h *history) {
			h.exec(t, "ALTER TABLE changesets ALTER COLUMN seq SET GENERATED BY DEFAULT")
			h.exec(t, "UPDATE changesets SET seq = 1000000 WHERE id = $1", h.root.ID[:])
		}, "seq", repo.VerifyOptions{}},
		{"mainline gap", func(t *testing.T, h *history) {
			h.exec(t, "DELETE FROM mainline WHERE changeset_id = $1", h.a.ID[:])
		}, "mainline", repo.VerifyOptions{}},
		{"mainline wrong row", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE mainline SET changeset_id = $1 WHERE changeset_id = $2", h.b.ID[:], h.a.ID[:])
		}, "mainline", repo.VerifyOptions{}},
		{"mainline above tip", func(t *testing.T, h *history) {
			h.exec(t, "INSERT INTO mainline (repo_id, ref_name, fp_depth, changeset_id) VALUES (1, 'main', 99, $1)", h.b.ID[:])
		}, "mainline", repo.VerifyOptions{}},
		{"dangling ref", func(t *testing.T, h *history) {
			h.exec(t, "UPDATE refs SET changeset_id = $1 WHERE name = 'release/1'", make([]byte, 32))
		}, "refs", repo.VerifyOptions{}},
		{"missing blob", func(t *testing.T, h *history) {
			removeObject(t, h, object.ID(object.KindBlob, []byte("y")))
		}, "objects", repo.VerifyOptions{Objects: true}},
		{"missing tree", func(t *testing.T, h *history) {
			e := lookupEntry(t, h, h.tail.Core.RootTree, "lib/x")
			removeObject(t, h, e)
		}, "objects", repo.VerifyOptions{Objects: true}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			h := newHistory(t)
			tt.tamper(t, h)
			report := h.verify(t, tt.opts)
			found := false
			for _, v := range report.Violations {
				if v.Check == tt.check {
					found = true
				}
			}
			if !found {
				t.Errorf("no %q violation; got %v", tt.check, report.Violations)
			}
		})
	}
}

func lookupEntry(t *testing.T, h *history, root hash.ID, path string) hash.ID {
	t.Helper()
	e, ok := lookup(t, h.env.Repo, root, path)
	if !ok {
		t.Fatalf("%s not found", path)
	}
	return e.ID
}

func removeObject(t *testing.T, h *history, id hash.ID) {
	t.Helper()
	if err := os.Remove(filepath.Join(h.storeDir, filepath.FromSlash(store.Key(id)))); err != nil {
		t.Fatal(err)
	}
}

func TestVerifyViolationString(t *testing.T) {
	t.Parallel()
	v := repo.Violation{Check: "mainline", Detail: "x"}
	if v.String() != "mainline: x" {
		t.Errorf("String = %q", v.String())
	}
	v.Changeset = hash.ID{0xab}
	if !strings.HasPrefix(v.String(), "ab0000000000 mainline") {
		t.Errorf("String = %q", v.String())
	}
}
